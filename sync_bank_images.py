"""Dò ảnh ngân hàng mà không sửa build_dashboard_data.py hay CSV Gemini."""
from pathlib import Path
import json, re, shutil, datetime
from urllib.parse import quote

ROOT=Path(__file__).resolve().parent
DASH=ROOT/"dashboard"
INDEX=DASH/"index.html"
OUT=DASH/"bank_images.js"
BANKS=("TCB","HDB","TPB","VPB","BID")
EXT={".png",".jpg",".jpeg",".webp",".jfif",".svg",".gif"}
ALIASES={
 "logo":("logo","logotype","brandmark","thuonghieu"),
 "background":("background","banner","cover","backdrop","hero","wallpaper","bg","nen"),
 "app":("app","smart","mobile","banking","interface","giaodien","screen","otp")
}
if not INDEX.exists():
 raise SystemExit("Dat sync_bank_images.py o thu muc bank_dx_rebuild (cung cap voi dashboard/).")

def norm(s):
 return re.sub(r"[^a-z0-9]","",s.lower())
def list_candidates(folder):
 return [f for f in folder.iterdir() if f.is_file() and f.suffix.lower() in EXT] if folder.exists() else []

mapped={}
for bank in BANKS:
 folder=ROOT/"assets"/"banks"/bank
 files=list_candidates(folder)
 chosen={}
 unused=set(files)
 for kind in ("logo","background","app"):
  exact=[f for f in files if norm(f.stem) in ALIASES[kind] and f in unused]
  fuzzy=[f for f in files if any(norm(a) in norm(f.stem) for a in ALIASES[kind]) and f in unused]
  match=(exact or fuzzy)
  if match:
   f=sorted(match,key=lambda x:(len(x.stem),x.name))[0]
   chosen[kind]="../assets/banks/"+bank+"/"+quote(f.name)
   unused.remove(f)
 mapped[bank]=chosen
 print(f"{bank}: "+(", ".join(f"{k}={Path(v).name}" for k,v in chosen.items()) if chosen else "Chua nhan dien duoc anh"))
 if files and len(chosen)<3:
  print("  Cac file trong folder:",", ".join(f.name for f in files))
 if not files:
  print("  KHONG TIM THAY:",folder)

js="/* Automatically generated by sync_bank_images.py; safe to regenerate. */\n"
js+="window.DBI=window.DBI||{};\nwindow.DBI.meta=window.DBI.meta||{};\n"
js+="window.DBI.meta.images=Object.assign({},window.DBI.meta.images||{},"+json.dumps(mapped,ensure_ascii=False)+");\n"
OUT.write_text(js,encoding="utf-8")
html=INDEX.read_text(encoding="utf-8")
if 'src="bank_images.js"' not in html:
 needle='<script src="assets/app.js"></script>'
 if needle not in html:
  raise SystemExit("Khong thay assets/app.js trong dashboard/index.html; can sua thu cong.")
 backup=INDEX.with_name("index.html.backup_"+datetime.datetime.now().strftime("%Y%m%d_%H%M%S"))
 shutil.copy2(INDEX,backup)
 html=html.replace(needle,'<script src="bank_images.js"></script>\n'+needle)
 INDEX.write_text(html,encoding="utf-8")
 print("Da chen bank_images.js vao index.html. Backup:",backup.name)
else:
 print("index.html da nhan bank_images.js, khong chen lai.")
print("OK. Mo lai http://localhost:8000/dashboard/ va Ctrl+Shift+R")
print("Luu y: build_dashboard_data.py chay tiep KHONG xoa bank_images.js.")
